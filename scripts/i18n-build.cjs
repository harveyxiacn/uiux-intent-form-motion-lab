#!/usr/bin/env node
/* Build docs/i18n/dict/<group>.<lang>.js from i18n/en/*.json and i18n/zh-TW/*.json.
   Translated batches (i18n/batches/en-XX.out.json) are first merged into i18n/en/<group>.json
   using en-XX.groups.json. Usage: node scripts/i18n-build.cjs [repoRoot] */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(process.argv[2] || path.join(__dirname, '..'));
const I = p => path.join(ROOT, 'i18n', p);
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));

// 1. merge batch outputs into per-group English files (existing entries are kept unless re-translated)
const en = {};
for (const f of fs.readdirSync(I('source'))) en[path.basename(f, '.json')] = fs.existsSync(I('en/' + f)) ? read(I('en/' + f)) : {};
const src = {};
for (const g of Object.keys(en)) src[g] = new Set(read(I('source/' + g + '.json')));
const bdir = I('batches');
if (fs.existsSync(bdir)) {
  for (const f of fs.readdirSync(bdir).filter(f => /^en-\d+\.out\.json$/.test(f))) {
    const out = read(path.join(bdir, f));
    // a string can appear in several groups; give the translation to every group that uses it
    for (const [k, v] of Object.entries(out)) for (const g of Object.keys(en)) if (src[g].has(k)) en[g][k] = v;
  }
}
// overrides (hand fixes found in QA) win over batch output
const ov = fs.existsSync(I('en-overrides.json')) ? read(I('en-overrides.json')) : {};
fs.mkdirSync(I('en'), { recursive: true });
const dict = path.join(ROOT, 'docs', 'i18n', 'dict');
fs.mkdirSync(dict, { recursive: true });
for (const g of Object.keys(en)) {
  const keys = read(I('source/' + g + '.json'));
  const sorted = {};
  for (const k of keys) if (en[g][k] != null) sorted[k] = en[g][k];
  for (const [k, v] of Object.entries(ov[g] || {})) sorted[k] = v;
  fs.writeFileSync(I('en/' + g + '.json'), JSON.stringify(sorted, null, 1) + '\n');
  const missing = keys.filter(k => sorted[k] == null).length;
  const tw = fs.existsSync(I('zh-TW/' + g + '.json')) ? read(I('zh-TW/' + g + '.json')) : {};
  for (const [lang, map] of [['en', sorted], ['zh-TW', tw]]) {
    fs.writeFileSync(path.join(dict, `${g}.${lang}.js`), `/* generated by scripts/i18n-build.cjs — edit i18n/*.json instead */\nI18N.add(${JSON.stringify(lang)}, ${JSON.stringify(map)});\n`);
  }
  console.log(`${g.padEnd(9)} en ${Object.keys(sorted).length}/${keys.length}${missing ? `  (${missing} missing)` : ''}  zh-TW ${Object.keys(tw).length}`);
}
const charsFile = I('zh-TW-chars.json');
if (fs.existsSync(charsFile)) {
  fs.writeFileSync(path.join(dict, 'chars.zh-TW.js'), `/* generated by scripts/i18n-build.cjs from i18n/zh-TW-chars.json */\nI18N.chars(${JSON.stringify(read(charsFile))});\n`);
}
